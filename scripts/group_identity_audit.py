"""Group-membership audit for sequence-paired rows (D35/D44).

Usage: python scripts/group_identity_audit.py <universe run dir> <prior-run tag> [--out docs/group-identity-audit.md]
For every holding flagged matched_by_sequence_tiebreak: its match group, row-level vs group-level identity, XBRL member
key / contexts / facts, the HTML row id consumed and every HTML row of the group, and a check that each HTML-derived
field retained on a group-level row carries the same value on every HTML row of the group (from html_rows.csv).
"""
from __future__ import annotations

import glob
import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def audit_run(run_dir: Path) -> list[dict]:
    h = pd.read_csv(run_dir / "holdings.csv", dtype=str, keep_default_na=False)
    hr = pd.read_csv(run_dir / "html_rows.csv", dtype=str, keep_default_na=False)
    rows_by = {(r.accession_number, r.row_id): json.loads(r.fields or "{}") for r in hr.itertuples()}
    t = h[h.review_flags.str.contains("matched_by_sequence_tiebreak")]
    out = []
    for r in t.itertuples():
        lineage = json.loads(r.field_lineage or "{}")
        group_ref = r.source_table if "group[" in (r.source_table or "") else ""
        group_rows = group_ref.split("group[")[1].rstrip("]").split(";") if group_ref else [r.html_row_id]
        html_fields = {k: v for k, v in lineage.items() if str(v.get("source", "")).startswith("html_cell")}
        disagreements = []
        for fld in html_fields:
            vals = {json.dumps(rows_by.get((r.accession_number, rid), {}).get(fld), sort_keys=True) for rid in group_rows}
            if len(vals) > 1:
                disagreements.append(fld)
        key = r.match_group_id or f"row:{r.holding_member_key}"
        out.append({
            "run": run_dir.name, "cik": r.cik, "accession": r.accession_number, "report_date": r.report_date, "holding_id": r.holding_id,
            "identity_resolution": r.identity_resolution, "match_group_id": key, "issuer": r.issuer, "xbrl_description": r.description,
            "xbrl_member_key": r.holding_member_key, "xbrl_context_ids": r.source_context_ids, "xbrl_fact_ids": r.source_fact_ids,
            "html_row_consumed": r.html_row_id, "html_rows_in_group": ";".join(group_rows), "fair_value": r.fair_value, "cost": r.cost, "principal_amount": r.principal_amount,
            "html_derived_fields_retained": ";".join(sorted(html_fields)), "html_fields_disagree_across_group": ";".join(disagreements),
            "group_dropped_fields": ";".join(f.split(":", 1)[1] for f in json.loads(r.review_flags) if f.startswith("group_field_dropped:")),
        })
    return out


def main(argv: list[str]) -> None:
    u = Path(argv[0]); tag = argv[1]
    out_md = Path(argv[argv.index("--out") + 1]) if "--out" in argv else ROOT / "docs" / "group-identity-audit.md"
    rows = audit_run(u)
    for d in sorted(glob.glob(str(ROOT / "output" / f"{tag}_*"))):
        rows += audit_run(Path(d))
    df = pd.DataFrame(rows)
    df.to_csv(u / "group_identity_audit.csv", index=False)
    n_flag = len(df); n_group = int((df.identity_resolution == "group").sum()); n_row = n_flag - n_group
    groups = df[df.identity_resolution == "group"].groupby(["accession", "match_group_id"]).size()
    row_groups = df[df.identity_resolution == "row"].groupby(["accession", "issuer", "fair_value", "cost", "principal_amount"]).size()
    consumed_unique = df.groupby("accession").apply(lambda g: g.html_row_consumed.is_unique).all()
    disagree = df[df.html_fields_disagree_across_group != ""]
    lines = ["# Group-membership audit: sequence-paired rows", "",
             f"Runs: `{u.name}` and `output/{tag}_*`; CSV with every source id: `{u.name}/group_identity_audit.csv`. Generated by `scripts/group_identity_audit.py`.", "",
             f"- Rows flagged `matched_by_sequence_tiebreak`: **{n_flag}** = row-level identity {n_row} (distinct, exactly agreeing descriptions on both sides) + group-level identity {n_group} (D44).",
             f"- Group-level groups: **{len(groups)}** (sizes {dict(Counter(groups.values))}); row-level pairings fall into {len(row_groups)} equal-valued groups (sizes {dict(Counter(row_groups.values))}); total equal-valued groups {len(groups) + len(row_groups)}.",
             f"- Multiplicity: every paired XBRL row consumes exactly one HTML row and no HTML row is consumed twice within a filing: {'yes' if consumed_unique else 'NO'}.",
             f"- Group-level rows whose retained HTML-derived fields differ across the group's HTML rows: **{len(disagree)}** (must be 0: differing fields are dropped with `group_field_dropped:<field>` and a `group_members_differ_no_row_identity` conflict).",
             f"- Group-level rows with dropped fields: {int((df.group_dropped_fields != '').sum())}.", "",
             "| Run | CIK | Accession | Group id | Identity | XBRL member | HTML row consumed | HTML rows in group | FV | Retained HTML fields | Disagreeing fields | Dropped |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for _, r in df.sort_values(["cik", "accession", "match_group_id", "holding_id"]).iterrows():
        lines.append(f"| {r.run} | {r.cik} | {r.accession} | {r.match_group_id[:60]} | {r.identity_resolution} | {r.xbrl_member_key[:70]} | {r.html_row_consumed} | {r.html_rows_in_group} | {r.fair_value} | {r.html_derived_fields_retained} | {r.html_fields_disagree_across_group} | {r.group_dropped_fields} |")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out_md, "flagged", n_flag, "group-level", n_group, "row-level", n_row, "group-level groups", len(groups), "row-level groups", len(row_groups), "disagreements", len(disagree))


if __name__ == "__main__":
    main(sys.argv[1:])
